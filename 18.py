# Standard vs Floor Division
print("Floor Division Demonstration")
a = 15
b = 4

print(f"Standard Division (15 / 4): {a / b}")   # 3.75
print(f"Floor Division (15 // 4): {a // b}")    # 3

# Handling Negatives
print(f"Negative Floor (-7 // 2): {-7 // 2}")  # -4

# Exponentiation basics
print("Exponentiation Demonstration")
base = 2
exp = 10

print(f"2 to the power of 10: {base ** exp}") # 1024

# Calculating roots using fractional exponents
# The square root of 25 is 25 raised to 0.5
print(f"Square root of 25: {25 ** 0.5}")       # 5.0